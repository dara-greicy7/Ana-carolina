import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";

// Mirrors images/ into public/hero-images and regenerates the manifest so the
// hero rotation works without runtime filesystem access (required on
// Cloudflare Workers, where the images/ directory does not exist at runtime).
const root = process.cwd();
const sourceDir = path.join(root, "images");
const targetDir = path.join(root, "public", "hero-images");
const manifestPath = path.join(root, "lib", "hero-manifest.ts");

const IMAGE_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"]);
const collator = new Intl.Collator(undefined, { numeric: true, sensitivity: "base" });

const files = fs.existsSync(sourceDir)
  ? fs
      .readdirSync(sourceDir, { withFileTypes: true })
      .filter(
        (entry) =>
          entry.isFile() && IMAGE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())
      )
      .map((entry) => entry.name)
      .sort((left, right) => collator.compare(left, right))
  : [];

fs.mkdirSync(targetDir, { recursive: true });

// Source photos are multi-megabyte camera exports; the hero never renders wider than
// ~1600px, so the public copies are downscaled to keep LCP fast. Originals in images/
// are never touched. sips ships with macOS; elsewhere we fall back to a plain copy.
const MAX_EDGE = "1600";
for (const file of files) {
  const from = path.join(sourceDir, file);
  const to = path.join(targetDir, file);
  const isJpeg = /\.jpe?g$/i.test(file);
  const resized =
    isJpeg &&
    spawnSync("sips", ["-Z", MAX_EDGE, "-s", "formatOptions", "62", from, "--out", to], { stdio: "ignore" })
      .status === 0;
  if (!resized) fs.copyFileSync(from, to);
}

for (const existing of fs.readdirSync(targetDir)) {
  if (!files.includes(existing)) {
    fs.unlinkSync(path.join(targetDir, existing));
  }
}

const manifest = `// Generated by scripts/sync-hero-images.mjs — do not edit by hand.
export const heroImageFiles: string[] = ${JSON.stringify(files, null, 2)};
`;
fs.writeFileSync(manifestPath, manifest);
console.log(`Synced ${files.length} hero images to public/hero-images`);
